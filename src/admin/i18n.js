/** 翻译：t('key', { var: value })；缺 key 回退英文，再回退 key 本身 */
export function t(key, vars) {
  const locale = adminLocale.value
  const table = messages[locale] || messages.en
  let text = table[key]
  if (text === undefined) text = messages.en[key]
  if (text === undefined) text = key
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m))
  }
  return text
}

/** 切换语言并持久化 */
export function setAdminLocale(code) {
  if (code !== 'en' && code !== 'zh-CN') return
  adminLocale.value = code
  try {
    localStorage.setItem(ADMIN_LOCALE_KEY, code)
  } catch { /* 隐私模式 */ }
}
