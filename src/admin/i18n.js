import { ref } from 'vue'

export const ADMIN_LOCALE_KEY = 'idolcal-admin-locale'

function detect() {
  try {
    const saved = localStorage.getItem(ADMIN_LOCALE_KEY)
    if (saved === 'en' || saved === 'zh-CN') return saved
    const site = localStorage.getItem('idolcal-locale')
    if (site === 'en' || site === 'zh-CN') return site
  } catch { /* SSR / 隐私模式 */ }
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

